// Writes lib/instrument-readout/vectors.json from lib/instrument-readout.ts:
// how a readout formats a raw value, and the pixels it writes with a strip -
// the cases the firmware and the app run too (device contract §2.15).
//
//   npx tsx scripts/readout-vectors.ts

import fs from "node:fs"
import path from "node:path"
import { drawReadout, formatReadout, READOUT_CHARS } from "../lib/instrument-readout"
import { rgb565Picture } from "../lib/needle-raster"
import { hex565 } from "../lib/instrument-needles"

const formats: { raw: string; decimals: number; expected?: string }[] = [
  { raw: "22.4", decimals: 1 },
  { raw: "22.45", decimals: 1 },
  { raw: "-0.04", decimals: 1 },
  { raw: "-0.05", decimals: 1 },
  { raw: "-12.5", decimals: 0 },
  { raw: "0", decimals: 2 },
  { raw: " 7 ", decimals: 0 },
  { raw: "1234.5678", decimals: 3 },
  { raw: "2.675", decimals: 2 },
  { raw: "1e3", decimals: 1 },
  { raw: "", decimals: 1 },
  { raw: "abc", decimals: 1 },
  { raw: "NaN", decimals: 1 },
  { raw: "999999.96", decimals: 1 },
  { raw: "12abc", decimals: 0 },
  { raw: "+5", decimals: 1 },
  { raw: "0x10", decimals: 0 },
  { raw: "-0x10", decimals: 0 },
  { raw: "0b101", decimals: 0 },
  { raw: "1f", decimals: 0 },
  { raw: "Infinity", decimals: 0 },
  { raw: ".5", decimals: 1 },
  { raw: "5.", decimals: 1 },
]
for (const f of formats) f.expected = formatReadout(f.raw, f.decimals)

// A made-up strip: each character a cell of its own, the alpha a pattern
// that tells the characters and every alpha step apart.
const pad = 2
const height = 9
const cells: [number, number, number][] = []
let x = 0
for (let i = 0; i < READOUT_CHARS.length; i++) {
  const advance = 4 + (i % 3)
  cells.push([x, advance + 2 * pad, advance])
  x += advance + 2 * pad
}
const width = x
const alpha = new Uint8Array(width * height)
for (let yy = 0; yy < height; yy++) for (let xx = 0; xx < width; xx++) alpha[yy * width + xx] = (xx * 37 + yy * 91 + ((xx * yy) % 7) * 13) % 256
const strip = { width, height, alpha: Array.from(alpha) }

const GROUND = hex565("#102030")
const draws = [
  { name: "right-aligned, lit", text: "-12.5", x: 30, y: 2, align: "right" as const, color: hex565("#3df5d0"), opacity: 256, w: 34, h: 13 },
  { name: "centred, lit", text: "7.0", x: 17, y: 1, align: "center" as const, color: hex565("#f2f4f7"), opacity: 256, w: 34, h: 13 },
  { name: "the unlit pattern, faint", text: "88.8", x: 30, y: 2, align: "right" as const, color: hex565("#3df5d0"), opacity: 20, w: 34, h: 13 },
  { name: "running off the left edge", text: "1234.5", x: 12, y: -3, align: "right" as const, color: hex565("#ff4a1f"), opacity: 256, w: 20, h: 8 },
].map((d) => {
  const pic = rgb565Picture(d.w, d.h, GROUND)
  drawReadout(pic, { chars: READOUT_CHARS, cells, pad, height, x: d.x, y: d.y, align: d.align, color: d.color }, { width, alpha }, d.text, d.opacity)
  return { ...d, ground: GROUND, expected: Array.from(pic.pixels, (c) => c.toString(16).padStart(4, "0")).join("") }
})

const out = {
  _comment:
    "Generated by scripts/readout-vectors.ts from lib/instrument-readout.ts. `formats`: formatReadout(raw, decimals). `draws`: drawReadout() of `text` with `strip` (chars, cells, pad, height as given) onto a w x h picture of `ground`; `expected` is RGB565, 4 hex digits a pixel, row by row.",
  formats,
  strip: { chars: READOUT_CHARS, cells, pad, ...strip },
  draws,
}
const file = path.join(__dirname, "..", "lib", "instrument-readout", "vectors.json")
fs.mkdirSync(path.dirname(file), { recursive: true })
fs.writeFileSync(file, JSON.stringify(out, null, 1) + "\n")
console.log(`wrote ${formats.length} formats and ${draws.length} draws to ${file}`)
