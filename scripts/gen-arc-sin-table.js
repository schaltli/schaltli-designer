#!/usr/bin/env node
/**
 * Emits the shared integer sine table used by the arc-level rasterizer, into
 * both the designer and the firmware, from this one source of truth.
 *
 * Why a table at all, and why generated rather than written twice:
 *
 * The arc rasterizer decides whether a sub-pixel lies inside the ring's
 * angular sector using cross products against the sector's two boundary
 * rays. Those rays need direction vectors, and a direction vector comes from
 * a sine and a cosine. If each side computed them with its own maths library
 * - V8's Math.sin in the browser, newlib's sinf on the ESP32 - the two would
 * agree to about fifteen digits and disagree in the last one. That sounds
 * harmless until you look at where it lands: along the shallow outer edge of
 * a radius-168 arc, the last digit is exactly what decides whether a
 * sub-pixel counts, and one sub-pixel is 1/16th of a pixel's coverage. The
 * pixel diff would then be small, non-zero, and different on every device -
 * the worst possible failure for a project whose entire verification method
 * is an exact comparison.
 *
 * With a table of integers there is nothing left to disagree about. Both
 * sides read the same numbers and multiply them the same way.
 *
 * Generating both files from here rather than pasting the table twice is the
 * same argument one level up: two hand-maintained copies of 360 numbers are
 * two copies that can drift, and a drift of one entry would be invisible in
 * review and produce a handful of wrong pixels at one angle.
 *
 * Run: node scripts/gen-arc-sin-table.js
 */

const fs = require("fs")
const path = require("path")

// 16384 = 2^14. Large enough that the direction vectors carry far more
// precision than the 1/8-pixel grid the rasterizer compares them against,
// small enough that cross products stay inside int32 on the device:
// 16384 * (8 * 360) * 2 is about 94 million, against int32's 2.1 billion.
const SCALE = 16384

const values = []
for (let deg = 0; deg < 360; deg++) {
  values.push(Math.round(Math.sin((deg * Math.PI) / 180) * SCALE))
}

// sin(180 deg) is 1.2e-16, not 0, and rounds to 0 - but assert rather than
// assume, because a table whose cardinal points are off by one would put a
// one-pixel notch at exactly the angles people choose most often.
const cardinals = { 0: 0, 90: SCALE, 180: 0, 270: -SCALE }
for (const [deg, expected] of Object.entries(cardinals)) {
  if (values[deg] !== expected) {
    throw new Error(`sine table is wrong at ${deg} deg: got ${values[deg]}, expected ${expected}`)
  }
}

function formatRows(indent) {
  const rows = []
  for (let i = 0; i < 360; i += 12) {
    rows.push(indent + values.slice(i, i + 12).map((v) => String(v).padStart(6)).join(", ") + ",")
  }
  return rows.join("\n")
}

const banner = `// GENERATED by scripts/gen-arc-sin-table.js in the designer repo.
// Do not edit: the designer and every firmware read the same numbers, and a
// hand edit here would desynchronise an arc-level's anti-aliased edge from
// what the designer draws. Regenerate instead.`

const tsPath = path.join(__dirname, "..", "lib", "arc-sin-table.ts")
fs.writeFileSync(
  tsPath,
  `${banner}

/** sin(deg) * ${SCALE}, rounded, for whole degrees 0..359. */
export const ARC_SIN_SCALE = ${SCALE}

export const ARC_SIN_TABLE: readonly number[] = [
${formatRows("  ")}
]
`,
)

const firmwareRepo = process.argv[2] || path.join(__dirname, "..", "..", "screenbee-waveshare-1v8")
const hPath = path.join(firmwareRepo, "src", "project", "ArcSinTable.h")
if (fs.existsSync(path.dirname(hPath))) {
  fs.writeFileSync(
    hPath,
    `#pragma once
#include <stdint.h>

${banner}

// sin(deg) * ${SCALE}, rounded, for whole degrees 0..359.
static const int32_t ARC_SIN_SCALE = ${SCALE};

static const int16_t ARC_SIN_TABLE[360] = {
${formatRows("    ")}
};
`,
  )
  console.log(`wrote ${tsPath}\nwrote ${hPath}`)
} else {
  console.log(`wrote ${tsPath}\nskipped firmware header - ${path.dirname(hPath)} not found`)
}
