#!/usr/bin/env node
// Writes the Android app's copy of the brand mark's outlines, from the one
// source both sides share: brand/glyphs.js.
//
//   node scripts/gen-brand-glyphs.js [<android repo>]
//
// Why generated rather than typed. The wordmark is real outlines cut from
// Varela Round, not a font the app loads - so the app has to carry the path
// data itself, and a hand-copied copy of 5 KB of curve numbers is a copy
// nobody will ever diff again. The same argument as scripts/gen-arc-sin-table
// .js, for the same reason: one source, several targets, and the targets are
// written rather than transcribed.
//
// The app parses these with androidx.compose.ui.graphics.vector.PathParser,
// which reads the same SVG path syntax the browser's Path2D does.

const fs = require("fs")
const path = require("path")

const glyphsPath = path.join(__dirname, "..", "brand", "glyphs.js")
const source = fs.readFileSync(glyphsPath, "utf8")
const json = source.slice(source.indexOf("{"), source.lastIndexOf("}") + 1)
const G = JSON.parse(json)

const vb = G.viewBox.trim().split(/\s+/).map(Number)
const banner = `// GENERATED by scripts/gen-brand-glyphs.js in the designer repo, from
// brand/glyphs.js. Do not edit by hand - re-run the generator.
//
// Varela Round (SIL Open Font License), converted to outlines. The baseline
// sits at y = 0 and the font size is ${G.fontSize}.`

const letters = G.letters
  .map((l) => `    "${l.d}",`)
  .join("\n")

const kt = `package com.schaltli.android.ui

${banner}
object BrandGlyphs {
    /** The viewBox the outlines are drawn in: minX, minY, width, height. */
    const val MIN_X = ${vb[0]}f
    const val MIN_Y = ${vb[1]}f
    const val WIDTH = ${vb[2]}f
    const val HEIGHT = ${vb[3]}f

    /** The pill at the end of the wordmark - the mark's moving part. */
    const val CAP_X = ${G.cap.x}f
    const val CAP_Y = ${G.cap.y}f
    const val CAP_W = ${G.cap.w}f
    const val CAP_H = ${G.cap.h}f
    const val BALL_R = ${G.cap.ballR}f

    /** SVG path data, one entry per letter, in drawing order. */
    val LETTERS: List<String> = listOf(
${letters}
    )
}
`

const check = process.argv.includes("--check")
const args = process.argv.slice(2).filter((a) => a !== "--check")
const androidRepo = args[0] || path.join(__dirname, "..", "..", "schaltli-android")
const outDir = path.join(androidRepo, "app", "src", "main", "java", "com", "schaltli", "android", "ui")
if (!fs.existsSync(androidRepo)) {
  // Exit 2, the code hil/test-all.js reads as SKIPPED: "the app is not checked
  // out here" is not an answer about whether the mark has drifted.
  console.error(`Android repo not found at ${androidRepo} - pass its path as the first argument.`)
  process.exit(2)
}
const outPath = path.join(outDir, "BrandGlyphs.kt")

// --check rather than a comparison somebody remembers to run: the outlines
// live in two places now, and the only thing that keeps them the same is
// something failing when they are not.
if (check) {
  const current = fs.existsSync(outPath) ? fs.readFileSync(outPath, "utf8") : null
  if (current === kt) {
    console.log(`up to date: ${outPath}`)
    process.exit(0)
  }
  console.error(
    current === null
      ? `MISSING: ${outPath}\nRegenerate it:  node scripts/gen-brand-glyphs.js`
      : `STALE: ${outPath} no longer matches brand/glyphs.js\nRegenerate it:  node scripts/gen-brand-glyphs.js`,
  )
  process.exit(1)
}

fs.mkdirSync(outDir, { recursive: true })
fs.writeFileSync(outPath, kt)
console.log(`wrote ${outPath} (${G.letters.length} letters, ${(kt.length / 1024).toFixed(1)} KB)`)
